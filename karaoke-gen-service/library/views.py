class PlaylistViewSet(viewsets.ModelViewSet):
    serializer_class = PlaylistSerializer
    permission_classes = [permissions.IsAuthenticated]

    def get_queryset(self):
        return Playlist.objects.filter(owner=self.request.user)

    def perform_create(self, serializer):
        serializer.save(owner=self.request.user)

    @action(detail=True, methods=["post"], url_path="add-song")
    def add_song(self, request, pk=None):
        playlist = self.get_object()
        song_id = request.data.get("song_id")

        if not song_id:
            return Response(
                {"detail": "song_id is required."},
                status=status.HTTP_400_BAD_REQUEST,
            )

        # Look up Song, calculate the next position,
        # then create PlaylistSong here.
        return Response(status=status.HTTP_201_CREATED)





class LibraryViewSet(viewsets.ModelViewSet):
    """
    CRUD API for the authenticated user's libraries.

    Generated by a DRF router:
        GET    /api/libraries/
        POST   /api/libraries/
        GET    /api/libraries/<id>/
        PUT    /api/libraries/<id>/
        PATCH  /api/libraries/<id>/
        DELETE /api/libraries/<id>/
    """

    serializer_class = LibrarySerializer
    permission_classes = [permissions.IsAuthenticated]

    def get_queryset(self):
        """
        Restrict every lookup to the current user's libraries.

        This also means requesting another user's library ID returns 404,
        not its data.
        """
        return (
            Library.objects
            .filter(owner=self.request.user)
            .select_related("owner")
            .prefetch_related(
                "librarysong_set__song",
                "libraryplaylist_set__playlist__playlistsong_set__song",
            )
            .order_by("name")
        )

    def perform_create(self, serializer):
        """
        Never accept the library owner from client JSON.
        The logged-in user becomes the owner.
        """
        serializer.save(owner=self.request.user)